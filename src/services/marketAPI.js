import api from './api';

export const marketAPI = {
  getAllMarketData: async () => {
    try {
      const response = await api.get('/market');
      if (response.data?.data?.marketData) {
        const serverData = response.data.data.marketData;
        const enriched = serverData.map((s) => {
          const seedMatch = SEED_MARKET_DATA.find((m) => m.cropName.toLowerCase() === s.cropName.toLowerCase());
          return {
            ...seedMatch,
            ...s,
            category: seedMatch?.category || 'Field Crops',
            pricePerQuintal: (s.pricePerKg || s.price) * 100,
            priceChange: seedMatch?.priceChange || '0.0%',
            arrivalQty: seedMatch?.arrivalQty || '2,400 Quintals',
            sellRecommendation: seedMatch?.sellRecommendation || s.marketInsight,
            history7Days: seedMatch?.history7Days || [],
          };
        });
        localStorage.setItem('agri_market_data', JSON.stringify(enriched));
        return { data: { data: { marketData: enriched, isDemo: true, dataSource: 'Live MySQL Connected Mandi Data' } } };
      }
    } catch (err) {
      console.warn('Backend unavailable, falling back to cached/seed market data.');
    }

    try {
      const raw = localStorage.getItem('agri_market_data');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length >= 15) {
          return { data: { data: { marketData: parsed, isDemo: true, dataSource: 'Sample Market Data (Step 1 Demo)' } } };
        }
      }
    } catch {}

    try {
      localStorage.setItem('agri_market_data', JSON.stringify(SEED_MARKET_DATA));
    } catch {}

    return { data: { data: { marketData: SEED_MARKET_DATA, isDemo: true, dataSource: 'Sample Market Data (Step 1 Demo)' } } };
  },

  getMarketDataByCrop: async (cropName) => {
    const res = await marketAPI.getAllMarketData();
    const list = res.data.data.marketData;
    const match = list.find((m) => m.cropName.toLowerCase() === (cropName || '').toLowerCase());
    return { data: { data: { marketData: match || list[0] } } };
  },
};
